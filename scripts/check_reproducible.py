#!/usr/bin/env python3
"""
check_reproducible.py - prove the published outputs are exactly what the code produces.

Run after a full rebuild (see README "Rebuild from source", or .github/workflows/validate.yml).
For every published output, compares the freshly rebuilt file with the committed copy
(`git show HEAD:<path>`):

  * CSV:   same columns and rows; text cells identical; numeric cells equal within 0.001
           (allows last-digit floating-point differences between machines, never a
           real change in a count)
  * JSON / GeoJSON: same structure; numbers within 0.001 (coordinates within 1e-5 deg)
  * XLSX:  every cell of every sheet, same rule (the file's own timestamps are ignored)

Exits non-zero, listing the first differences, if anything differs.

Known exception (README "Known issues"): data/results_long_2008-general-precinct-geom-clean.csv
and data/omitted_2008-general-precinct.csv are not regenerated by the current code until
the OCR label fix lands; the rebuild keeps the committed copies, so they are not compared.

Run (from the repository root):
    python3 scripts/check_reproducible.py
"""
import io, json, subprocess, sys
from pathlib import Path

import pandas as pd

from paths import ROOT

OUTPUTS = [
    "data/results_long_all.csv",
    "data/results_long_2022-primary-precinct-geom-clean.csv",
    "data/omitted_2022-primary-precinct.csv",
    "data/turnout_long.csv",
    "data/boone_county_election_results.xlsx",
    "data/normalized/results_by_current_district.csv",
    "data/normalized/precinct_district_shares.csv",
    "data/normalized/election_precinct_map.csv",
    "data/normalized/set_aside.csv",
    "data/normalized/normalization_validation.csv",
    "data/normalized/current_districts.geojson",
    "data/normalized/results_by_district_as_drawn.csv",
    "data/normalized/precinct_district_as_drawn.csv",
    "data/normalized/as_drawn_validation.csv",
    "site/data/results.json",
    "site/data/precincts_2010.geojson",
    "site/data/precincts_2024.geojson",
    "site/data/districts.geojson",
]
TOL, COORD_TOL = 1e-3, 1e-5


def committed(path):
    return subprocess.run(["git", "-C", str(ROOT), "show", f"HEAD:{path}"],
                          check=True, capture_output=True).stdout


def _num(s):
    try:
        return float(s)
    except (TypeError, ValueError):
        return None


def compare_csv(path):
    old = pd.read_csv(io.BytesIO(committed(path)), dtype=str, keep_default_na=False)
    new = pd.read_csv(ROOT / path, dtype=str, keep_default_na=False)
    if list(old.columns) != list(new.columns):
        return [f"columns differ: {list(old.columns)} vs {list(new.columns)}"]
    if len(old) != len(new):
        return [f"{len(old)} rows committed, {len(new)} rebuilt"]
    diffs = []
    for col in old.columns:
        for i, (a, b) in enumerate(zip(old[col], new[col])):
            if a == b:
                continue
            x, y = _num(a), _num(b)
            if x is not None and y is not None and abs(x - y) <= TOL:
                continue
            diffs.append(f"row {i + 2}, {col}: {a!r} -> {b!r}")
            if len(diffs) >= 5:
                return diffs
    return diffs


def compare_tree(a, b, where="", tol=TOL, out=None):
    out = [] if out is None else out
    if len(out) >= 5:
        return out
    if isinstance(a, dict) and isinstance(b, dict):
        if set(a) != set(b):
            out.append(f"{where}: keys differ ({sorted(set(a) ^ set(b))[:5]})")
        for k in set(a) & set(b):
            compare_tree(a[k], b[k], f"{where}/{k}", COORD_TOL if k == "coordinates" else tol, out)
    elif isinstance(a, list) and isinstance(b, list):
        if len(a) != len(b):
            out.append(f"{where}: length {len(a)} vs {len(b)}")
        for i, (x, y) in enumerate(zip(a, b)):
            compare_tree(x, y, f"{where}[{i}]", tol, out)
    elif isinstance(a, (int, float)) and isinstance(b, (int, float)) and not isinstance(a, bool):
        if abs(a - b) > tol:
            out.append(f"{where}: {a} -> {b}")
    elif a != b:
        out.append(f"{where}: {a!r} -> {b!r}")
    return out


def compare_json(path):
    return compare_tree(json.loads(committed(path)), json.loads((ROOT / path).read_text()))


def compare_xlsx(path):
    from openpyxl import load_workbook
    old = load_workbook(io.BytesIO(committed(path)), read_only=True)
    new = load_workbook(ROOT / path, read_only=True)
    sheets = lambda wb: {ws.title: [list(r) for r in ws.iter_rows(values_only=True)] for ws in wb.worksheets}
    return compare_tree(sheets(old), sheets(new))


def main():
    failed = 0
    for path in OUTPUTS:
        if not (ROOT / path).exists():
            print(f"MISSING    {path}"); failed += 1; continue
        ext = Path(path).suffix
        diffs = (compare_csv(path) if ext == ".csv" else
                 compare_xlsx(path) if ext == ".xlsx" else compare_json(path))
        if diffs:
            failed += 1
            print(f"DIFFERENT  {path}")
            for d in diffs:
                print(f"     {d}")
        else:
            print(f"SAME       {path}")
    print(f"\nRESULT: {'PASS - every published output is reproduced by the code' if not failed else f'FAIL - {failed} file(s) differ'}")
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
