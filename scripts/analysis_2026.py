#!/usr/bin/env python3
"""
analysis_2026.py - write the 2026 general election analysis (analysis/2026_general.md).

Every number in the report is computed here from the published tables; none is typed. Rerun
it after the county certifies (replace the PDF, update scripts/provisional.py, rerun the
pipeline) and every figure updates.

Inputs  : data/results_long_all.csv (Results_Long), data/turnout_long.csv,
          data/normalized/results_by_current_district.csv, source_geo/precincts_2024.geojson
Outputs : analysis/2026_general.md          the written report
          analysis/2026_general_tables.csv  every number the report quotes, one row each

Comparisons are midterm to midterm (2026 vs 2022): 2026 had no President, Governor or U.S.
Senate race, so the statewide offices on every ballot in both years carry the comparison.
Both years use today's 53 precincts and today's district lines, so district figures are
exact sums of whole precincts (no estimation).

Wording is deliberately neutral: margins name the party ahead ("Republican +12.3");
shifts name the direction ("toward Democratic by 4.1 points"). No lean/safe labels.

Run (from the repository root, after normalize.py):
    python3 scripts/analysis_2026.py
"""
import csv
from datetime import date

import geopandas as gpd
import pandas as pd

from paths import DATA_DIR, ROOT
from provisional import PROVISIONAL
from make_maps import CONTESTS, key, load_results, contest_rows, precinct_margins

OUT = ROOT / "analysis"
Y0, Y1 = "2022", "2026"
OFFICES = [("Secretary of State", r"^SECRETARY OF STATE"),
           ("Auditor of State / State Comptroller", r"AUDITOR OF STATE|COMPTROLLER"),
           ("Treasurer of State", r"^TREASURER OF STATE"),
           ("U.S. House District 4", CONTESTS["us_house_4"][1])]
DISTRICTS = [("in_house", d, f"Indiana House {d}") for d in ["24", "25", "28", "41"]] + \
            [("in_senate", d, f"Indiana Senate {d}") for d in ["7", "29"]]
TABLE = []   # every quoted number: (section, item, year_or_change, value)


def note(section, item, field, value):
    TABLE.append({"section": section, "item": item, "field": field,
                  "value": "" if value is None else round(value, 4) if isinstance(value, float) else value})
    return value


def margin(R, D):
    return 100 * (R - D) / (R + D) if (R + D) else None


def fmt_margin(m):
    if m is None: return "–"
    if abs(m) < 0.05: return "Even"
    return f"{'Republican' if m > 0 else 'Democratic'} +{abs(m):.1f}"


def fmt_shift(s):
    if s is None: return "–"
    if abs(s) < 0.05: return "no change"
    return f"{abs(s):.1f} toward {'Republican' if s > 0 else 'Democratic'}"


def table(headers, rows):
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def main():
    results = load_results()
    norm = pd.read_csv(DATA_DIR / "normalized/results_by_current_district.csv",
                       dtype={"district": str, "party": str}, keep_default_na=False)
    p24 = gpd.read_file(ROOT / "source_geo/precincts_2024.geojson")
    p24["pkey"] = p24["precinct_name_raw"].map(key)
    dist_of = p24.set_index("pkey")[["in_house", "in_senate"]]
    md = []

    # ---------------------------------------------------------------- header
    prov = PROVISIONAL.get(f"{Y1}-GENERAL")
    md.append(f"# {Y1} general election in Boone County, Indiana\n")
    md.append(f"*Generated by `scripts/analysis_2026.py` on {date.today().isoformat()} from the published "
              f"tables; every figure below is computed, none is typed.*\n")
    if prov:
        md.append(f"> **Provisional.** The {Y1} figures come from the Clerk's {prov}. They will be "
                  f"replaced by the certified canvass when it is posted, and this report regenerated.\n")

    # ---------------------------------------------------------------- turnout
    t = pd.read_csv(DATA_DIR / "turnout_long.csv", dtype=str)
    turn = {}
    for y in (Y0, Y1):
        tt = t[t["source_file_id"] == f"{y}-GENERAL-PRECINCT"].copy()
        pr = tt[tt["granularity"] == "precinct"].copy()
        # County = sum of precinct rows (some elections, e.g. 2022 general, have no countywide
        # turnout row). Where a countywide row exists, it must agree with that sum.
        reg, pub = pr["registered_voters"].astype(int).sum(), pr["public_count"].astype(int).sum()
        cw = tt[tt["granularity"] == "countywide"]
        if len(cw) and (int(cw.iloc[0]["registered_voters"]), int(cw.iloc[0]["public_count"])) != (reg, pub):
            raise SystemExit(f"STOP: {y} countywide turnout row disagrees with the sum of its precincts")
        turn[(y, "county")] = (reg, pub)
        pr["pkey"] = pr["precinct_name"].map(key)
        pr = pr.join(dist_of, on="pkey")
        if pr["in_house"].isna().any():
            raise SystemExit(f"STOP: {y} turnout precincts without a current district: "
                             f"{sorted(pr[pr['in_house'].isna()]['precinct_name'])}")
        for dt, d, _ in DISTRICTS:
            s = pr[pr[dt] == d]
            turn[(y, f"{dt}{d}")] = (s["registered_voters"].astype(int).sum(), s["public_count"].astype(int).sum())
    rows = []
    for k, label in [("county", "Boone County")] + [(f"{dt}{d}", lbl) for dt, d, lbl in DISTRICTS]:
        (r0, b0), (r1, b1) = turn[(Y0, k)], turn[(Y1, k)]
        p0, p1 = 100 * b0 / r0, 100 * b1 / r1
        note("turnout", label, f"{Y0} turnout %", p0); note("turnout", label, f"{Y1} turnout %", p1)
        note("turnout", label, f"{Y1} ballots", b1)
        rows.append([label, f"{b0:,} of {r0:,} ({p0:.1f}%)", f"{b1:,} of {r1:,} ({p1:.1f}%)", f"{p1 - p0:+.1f}"])
    md.append("## Turnout\n")
    md.append(f"Ballots cast ÷ registered voters, as printed in the Clerk's reports. {Y0} and {Y1} are both "
              f"midterm elections. District rows are sums of today's whole precincts (Boone County part only).\n")
    md.append(table(["Area", f"{Y0}", f"{Y1}", "Change (points)"], rows) + "\n")

    # ---------------------------------------------------------------- statewide offices, county
    md.append(f"## Statewide offices on both ballots, countywide\n")
    md.append(f"These offices were on every precinct's ballot in {Y0} and {Y1} and contested by both "
              f"parties, so they are the like-for-like comparison. Margin = (Republican − Democratic) ÷ "
              f"(Republican + Democratic). The candidates differ between years.\n")
    rows, county_m = [], {}
    for label, pat in OFFICES:
        ms = []
        for y in (Y0, Y1):
            r_, office = contest_rows(results, y, pat)
            R, D = r_[r_.party == "R"]["votes"].sum(), r_[r_.party == "D"]["votes"].sum()
            other = r_[~r_.party.isin(["R", "D"])]["votes"].sum()
            m = note("county", label, f"{y} margin", margin(R, D))
            note("county", label, f"{y} other-candidate share %", 100 * other / (R + D + other))
            ms.append(m)
        county_m[label] = ms
        sh = note("county", label, "shift", ms[1] - ms[0])
        rows.append([label, fmt_margin(ms[0]), fmt_margin(ms[1]), fmt_shift(sh)])
    md.append(table(["Office", Y0, Y1, "Shift (points)"], rows) + "\n")

    # ---------------------------------------------------------------- statewide offices, districts
    md.append("## By today's legislative districts\n")
    md.append("Same offices, Boone County part of each of today's districts. Both years are on today's "
              "lines, so these are exact sums of whole precincts.\n")
    def dmargin(office_pat, y, dt, d):
        s = norm[(norm["election"] == f"{y}-GENERAL") & (norm["district_type"] == dt) & (norm["district"] == d)
                 & norm["office"].str.upper().str.contains(office_pat, regex=True)]
        return margin(s[s.party == "R"]["votes"].sum(), s[s.party == "D"]["votes"].sum())
    for label, pat in OFFICES:
        rows = []
        for dt, d, dl in DISTRICTS:
            a, b = dmargin(pat, Y0, dt, d), dmargin(pat, Y1, dt, d)
            note("district", f"{label} | {dl}", f"{Y0} margin", a); note("district", f"{label} | {dl}", f"{Y1} margin", b)
            sh = note("district", f"{label} | {dl}", "shift", b - a)
            rows.append([dl, fmt_margin(a), fmt_margin(b), fmt_shift(sh)])
        md.append(f"**{label}**\n\n" + table(["District (Boone part)", Y0, Y1, "Shift (points)"], rows) + "\n")

    # ---------------------------------------------------------------- secretary of state, long run
    label, pat, years = CONTESTS["secretary_of_state"]
    rows = []
    for y in years:
        r_, _ = contest_rows(results, y, pat)
        m = note("secretary_of_state", "Boone County", f"{y} margin",
                 margin(r_[r_.party == "R"]["votes"].sum(), r_[r_.party == "D"]["votes"].sum()))
        rows.append([y, fmt_margin(m) + (" (provisional)" if f"{y}-GENERAL" in PROVISIONAL else "")])
    md.append("## Secretary of State, every midterm since 2010\n")
    md.append("The one statewide race on every Boone ballot in each midterm: the longest like-for-like "
              "series available for years without a top-of-ticket race. (2008 is omitted while its scanned "
              "results are under review.)\n")
    md.append(table(["Year", "Boone County margin"], rows) + "\n")

    # ---------------------------------------------------------------- precinct shifts
    sp = []
    for y in (Y0, Y1):
        r_, _ = contest_rows(results, y, OFFICES[0][1])
        pm = precinct_margins(r_); pm["pkey"] = pm["precinct_name"].map(key); sp.append(pm[["pkey", "precinct_name", "margin"]])
    sw = sp[1].merge(sp[0][["pkey", "margin"]], on="pkey", suffixes=("_1", "_0"))
    sw["shift"] = sw["margin_1"] - sw["margin_0"]
    sw = sw.join(dist_of, on="pkey")
    n_d, n_r = int((sw["shift"] < 0).sum()), int((sw["shift"] > 0).sum())
    note("precinct_shift", "Secretary of State", "precincts toward Democratic", n_d)
    note("precinct_shift", "Secretary of State", "precincts toward Republican", n_r)
    note("precinct_shift", "Secretary of State", "median shift", float(sw["shift"].median()))
    md.append(f"## Precinct shifts, Secretary of State {Y0} → {Y1}\n")
    md.append(f"Of {len(sw)} precincts, **{n_d}** shifted toward the Democratic candidate and **{n_r}** "
              f"toward the Republican candidate; the median shift was "
              f"{fmt_shift(float(sw['shift'].median())).replace(' toward', ' points toward')}. "
              f"Map: `maps/swing_secretary_of_state_{Y0}_{Y1}.png`.\n")

    def shift_table(part):
        rows = [[r.precinct_name, f"House {r.in_house}", fmt_margin(r.margin_0), fmt_margin(r.margin_1),
                 fmt_shift(r.shift)] for r in part.itertuples()]
        return table(["Precinct", "District", Y0, Y1, "Shift (points)"], rows) + "\n"

    # Name each table for what it actually contains: if no precinct moved one way, the
    # "other end" of the list is the smallest shifts in the SAME direction, and says so.
    toward_d, toward_r = sw[sw["shift"] < 0], sw[sw["shift"] > 0]
    if len(toward_d):
        md.append("Largest shifts toward Democratic:\n\n" + shift_table(toward_d.nsmallest(5, "shift")))
    if len(toward_r):
        md.append("Largest shifts toward Republican:\n\n" + shift_table(toward_r.nlargest(5, "shift")))
    for direction, rest in [("Republican", toward_d), ("Democratic", toward_r)]:
        other = toward_r if direction == "Republican" else toward_d
        if not len(other) and len(rest):
            md.append(f"No precinct shifted toward the {direction} candidate. Smallest shifts:\n\n" +
                      shift_table(rest.loc[rest["shift"].abs().nsmallest(5).index]))

    # ---------------------------------------------------------------- method
    g26 = results[results["election"] == f"{Y1}-GENERAL"]
    vf1 = g26[g26["vote_for"].isin(["1", "1.0"])].groupby(["precinct_id", "office", "contest_party"])
    n_contests = note("validation", f"{Y1} general", "single-winner contests", int(vf1.ngroups))
    n_ok = note("validation", f"{Y1} general", "contests whose totals equal VOTES=",
                int(sum(1 for _, g in vf1 if g["votes"].sum() == float(g["contest_votes"].iloc[0]))))
    md.append("## Method and caveats\n")
    md.append(f"- Source: Boone County Clerk precinct reports, parsed and validated as described in "
              f"METHODOLOGY.md. In the {Y1} general, {n_ok:,} of {n_contests:,} single-winner precinct "
              f"contests have candidate totals equal to the report's own printed contest total, and the "
              f"precinct rows were also checked against the Clerk's separate countywide summary "
              f"(`scripts/reconcile_all.py`).\n"
              "- Only the two-party vote is in the margin; third-party and write-in votes are excluded "
              "(their share is in `analysis/2026_general_tables.csv`).\n"
              "- Different candidates ran in each year, so a shift describes how the same places voted "
              "for different contests, not a change in any individual's support.\n"
              "- District figures cover only the part of each district inside Boone County.\n"
              "- Maps: `maps/margin_secretary_of_state.png`, `maps/margin_us_house_4.png`, "
              f"`maps/statewide_offices_{Y0}_{Y1}.png`, `maps/turnout_{Y1}_general.png`, and the "
              "interactive map.\n")

    OUT.mkdir(exist_ok=True)
    (OUT / "2026_general.md").write_text("\n".join(md))
    with open(OUT / "2026_general_tables.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["section", "item", "field", "value"]); w.writeheader(); w.writerows(TABLE)
    print(f"Wrote analysis/2026_general.md and analysis/2026_general_tables.csv ({len(TABLE)} numbers)")


if __name__ == "__main__":
    main()
